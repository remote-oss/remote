import {deepStrictEqual, rejects, strictEqual} from 'node:assert';
import {existsSync, readFileSync} from 'node:fs';
import path from 'node:path';
import {checkIdentifiers, generateTables} from './identifiers.ts';
import {TemporaryWorkspace} from './temporary-workspace.ts';

const INVENTORY_NOTE =
  'reference inventory comparison skipped: no spec repository publishes tests/conformance/identity-inventory.json yet';

const DECLARED = {
  source: 'remote-oss/remote-x#1 (F-0001)',
  standsDownFor: 'ms-vscode-remote.remote-x',
};

describe('identifiers', () => {
  let workspace: TemporaryWorkspace;

  function tablePath(folder: string): string {
    return path.join(
      workspace.root,
      'packages',
      folder,
      'src/identifiers.generated.ts',
    );
  }

  function writeCodePackage(folder: string, contributes: object): void {
    workspace.writeManifest(folder, {contributes});
    workspace.write(`packages/${folder}/identifiers.json`, DECLARED);
    workspace.write(`packages/${folder}/src/extension.ts`, '');
  }

  beforeEach(() => {
    workspace = new TemporaryWorkspace('identifiers');
  });

  afterEach(() => {
    workspace.remove();
  });

  describe('generate', () => {
    it('writes a formatted table into a package with src/', async () => {
      writeCodePackage('remote-x', {languages: [{id: 'ssh_config'}]});
      await generateTables(workspace.root);
      strictEqual(
        readFileSync(tablePath('remote-x'), 'utf8'),
        [
          '/**',
          ' * @fileoverview The identifiers of packages/remote-x, generated by tools/identifiers.ts from its',
          ' * package.json and identifiers.json. `pnpm identifiers` writes it again.',
          ' */',
          '',
          '/** The language ids of `contributes.languages`. */',
          'export const languages = {',
          "  sshConfig: 'ssh_config',",
          '} as const;',
          '',
        ].join('\n'),
      );
    });

    it('reports each package with src/ and skips the others', async () => {
      writeCodePackage('remote-x', {languages: [{id: 'ssh_config'}]});
      writeCodePackage('remote-y', {});
      workspace.writeManifest('remote-z');
      deepStrictEqual(await generateTables(workspace.root), [
        'remote-x: src/identifiers.generated.ts',
        'remote-y: no identifiers, no table',
      ]);
    });

    it('removes a table whose kinds became empty', async () => {
      writeCodePackage('remote-x', {});
      workspace.write('packages/remote-x/src/identifiers.generated.ts', 'old');
      await generateTables(workspace.root);
      strictEqual(existsSync(tablePath('remote-x')), false);
    });

    it('fails for a package with src/ and no identifiers.json', async () => {
      workspace.writeManifest('remote-x');
      workspace.write('packages/remote-x/src/extension.ts', '');
      await rejects(generateTables(workspace.root), {
        message:
          'packages/remote-x: identifiers.json is missing; a package with src/ needs one',
      });
    });
  });

  describe('check', () => {
    it('passes packages without code or identifiers.json, noting the skipped inventory', () => {
      workspace.writeManifest('remote-x');
      deepStrictEqual(checkIdentifiers(workspace.root), {
        problems: [],
        notes: [INVENTORY_NOTE],
      });
    });

    it('reports a package with src/ and no identifiers.json', () => {
      workspace.writeManifest('remote-x');
      workspace.write('packages/remote-x/src/extension.ts', '');
      deepStrictEqual(checkIdentifiers(workspace.root).problems, [
        'packages/remote-x: identifiers.json is missing; a package with src/ needs one',
      ]);
    });

    it('prefixes rule problems and notes with the package', () => {
      workspace.writeManifest('remote-x');
      workspace.write('packages/remote-x/identifiers.json', {
        ...DECLARED,
        standingDownKey: '',
        infoLineCommands: ['remote-x.gone'],
      });
      deepStrictEqual(checkIdentifiers(workspace.root), {
        problems: [
          "packages/remote-x: infoLineCommands names 'remote-x.gone', which is not a contributed command",
        ],
        notes: [
          INVENTORY_NOTE,
          'packages/remote-x: stand-down gating pending: standingDownKey is empty',
        ],
      });
    });

    it('reports a source that cannot be read and goes on', () => {
      workspace.write('packages/remote-x/package.json', '{');
      workspace.writeManifest('remote-y');
      deepStrictEqual(checkIdentifiers(workspace.root).problems.length, 1);
    });
  });
});
